        public static float[][] TableFor(byte mode) => mode == 2 ? Ts : Ra2;

        /// <summary>越界索引兜底指向上方（+Z）。</summary>
        public static float[] Get(byte mode, int index)
        {
            var table = TableFor(mode);
            if (index >= 0 && index < table.Length) return table[index];
            return Up;
        }

        public static readonly float[] Up = new float[] { 0f, 0f, 1f };
    }
